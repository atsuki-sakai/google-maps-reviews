import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../../src/google_maps_reviews/extract_reviews.js', import.meta.url);
const target = new URL('../src/lib/extractor.ts', import.meta.url);
try {
  const text = await readFile(source, 'utf8');
  await writeFile(target, '// Generated by scripts/sync-extractor.mjs from the shared DOM extractor.\nexport const extractorSource = ' + JSON.stringify(text) + ';\n');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  await readFile(target, 'utf8');
}
